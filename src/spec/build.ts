/** Every file the spec has, by path from the root: spec/… and llms.txt. Throws if a worked example is wrong. */
export async function buildSpec(root: string): Promise<Record<string, string>> {
  const r: Repo = { root };
  const wrong = [...await wrongExamples(), ...wrongInternalExamples()];
  if (wrong.length) throw new Error(`These worked examples don't say what the code gives (src/spec/rules.ts):\n${wrong.join('\n')}`);
  const mods = moduleFacts(r);
  const tests = testIndex(r);
  const reqText = new Map(requirements(r).requirements.map((q) => [q.id, q.text]));
  const out: Record<string, string> = {
    'llms.txt': systemOverview(),
    'spec/README.md': readme(mods),
    'spec/core/data-model.md': GENERATED('src/domain/types.ts and supabase/migrations') + dataModelMarkdown(r),
    'spec/core/vocabulary.md': vocabulary(),
    'spec/core/rules/README.md': rulesIndex(),
    'spec/core/screens.md': screens(r),
    'spec/core/journeys.md': journeys(r, mods),
    'spec/core/requirements.md': requirementsPage(r, mods, tests),
    'spec/modules/README.md': modulesIndex(mods),
  };
  for (const rule of RULE_LIST) out[`spec/core/rules/${rule.id}.md`] = rulePage(rule, tests, reqText);
  for (const m of mods) out[`spec/modules/${m.id}/README.md`] = modulePage(m, r, tests, stages(mods).find((s) => s.module === m.id));
  const { buildPlatformOrg } = await import('../data/platformOrg/generate');
  const w = conformanceWorkspace(buildPlatformOrg(new Date(CHECK_IN_MOMENT)));
  const files = conformanceFiles(w);
  out['spec/conformance/workspace.json'] = workspaceJson(w);
  for (const [f, text] of Object.entries(files)) out[`spec/conformance/${f}`] = text;
  out['spec/conformance/README.md'] = conformanceReadme(w, files);
  const rows = Object.fromEntries(Object.entries(files).map(([f, text]) => [f.replace('.csv', ''), text.trimEnd().split('\n').length - 1]));
  Object.assign(out, internalFiles());
  Object.assign(out, rebuildFiles(mods as ModuleWithRebuild[], rows, read(r, 'scripts/drill.mjs')));
  return out;
}

