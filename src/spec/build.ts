/* ---------- screens ---------- */

function screens(r: Repo): string {
  const routes = coreRoutes(r);
  const byFile = new Map<string, typeof routes>();
  for (const x of routes) byFile.set(x.file, [...(byFile.get(x.file) ?? []), x]);
  const articleFor = (path: string, component: string, file: string): Article | undefined => {
    const name = file.split('/').pop()!.replace('.tsx', '');
    return ARTICLES.find((a) => !a.module && a.routes.includes(path)) ?? ARTICLES.find((a) => !a.module && a.screens.includes(component)) ?? ARTICLES.find((a) => !a.module && a.screens.includes(name));
  };
  const out = [GENERATED('src/App.tsx, src/screens, src/help/guide.ts and src/mcp/parity.ts'), '# The core screens', '',
    'Each core route (as `src/App.tsx` writes it), the screen behind it, its purpose (its Help article’s summary, `src/help/guide.ts`), its named parts (the headings and labelled regions its markup writes), its one main action (`src/spec/screens.ts`, the one part written by hand), the primary buttons its markup writes (one shows at a time) and the AI tools that read or do the same (`src/mcp/parity.ts`). Every screen has one primary action at a time; a screen that steps through a flow (a check-in, a wizard) shows one per step, so all its primary buttons are listed.',
    '', `Feature modules add their own screens: see [the modules](../modules/README.md). ${UNCLEAR} names and actions are read from the markup as written; a heading or button whose words are worked out when it shows (from the goal, the person or the week) is not listed. The Help article and the eval journeys show those.`, ''];
  for (const [file, rs] of byFile) {
    const name = file.split('/').pop()!.replace('.tsx', '');
    const parts = screenParts(r, file);
    const tools = SCREENS[name];
    out.push(`## ${name}`, '', `${link(2, file)}`, '');
    for (const x of rs) {
      const a = articleFor(x.path, x.component, file);
      out.push(`- \`${x.path}\` (\`${x.component}\`)${a ? `: ${cell(a.summary)} Help: “${a.title}” (\`${a.id}\`).` : ''}`);
    }
    out.push('');
    out.push(`- **Named parts:** ${parts.headings.length || parts.regions.length ? [...parts.headings, ...parts.regions.map((x) => `${x} (region)`)].map((x) => `“${cell(x)}”`).join(', ') : 'none written as plain text'}`);
    out.push(`- **Main action:** ${MAIN_ACTION[name] ?? '(none written: add it to src/spec/screens.ts)'}`);
    out.push(`- **Primary buttons in its markup:** ${parts.primary.length ? parts.primary.map((x) => `“${cell(x)}”`).join(', ') : 'none written as plain text'}`);
    out.push(`- **AI tools:** ${!tools ? 'none listed' : Array.isArray(tools) ? tools.map((t) => `\`${t}\``).join(', ') : `none, on purpose: ${tools.notForAssistants}`}`);
    out.push('');
  }
  return out.join('\n');
}

/* ---------- journeys and requirements ---------- */

const moduleIds = (mods: ModuleFacts[]) => new Set(mods.flatMap((m) => m.journeys));
const moduleReqs = (mods: ModuleFacts[]) => new Set(mods.flatMap((m) => m.requirements));

function journeys(r: Repo, mods: ModuleFacts[]): string {
  const req = requirements(r);
  const ranked = new Map(req.journeys.map((j) => [j.id, j]));
  const theirs = moduleIds(mods);
  const all = checks(r).filter((c) => !theirs.has(c.id));
  const kinds: [Check['kind'], string, string][] = [
    ['journey', 'Journeys', 'Each drives the built app in Chromium as a person would, on a phone (390px) and a desktop (1440px), and is scored on the ten-point ease test below. `budget` is the most steps it may take.'],
    ['platform', 'Platform checks', 'Checks run across every screen: design rules, widths, motion, errors.'],
    ['finish', 'Fit and finish', 'Per-area checks from the fit-and-finish reports.'],
    ['note', 'Review notes', 'Checks that Lane’s review notes stay fixed.'],
  ];
  const out = [GENERATED('evals/journeys.cjs, evals/finish, evals/notes and evals/requirements.json'), '# The core journeys', '',
    `What people do with Faro end to end, and the checks that drive it (\`npm run evals\`; \`${link(2, 'evals/journeys.cjs')}\`). Journeys and checks a module owns are in its own section (${mods.map((m) => `[${m.name}](../modules/${m.id}/README.md)`).join(', ') || 'none'}). Who the journeys are for: \`docs/journeys.md\`.`, ''];
  for (const [kind, title, about] of kinds) {
    const list = all.filter((c) => c.kind === kind);
    if (!list.length) continue;
    out.push(`## ${title}`, '', about, '');
    out.push(table(kind === 'journey' ? ['Id', 'Journey', 'Who', 'Requirements', 'Budget', 'Where'] : ['Id', 'Check', 'Requirements', 'Where'], list.map((c) => {
      const j = ranked.get(c.id);
      return kind === 'journey'
        ? [c.id, cell(c.title), cell(j?.who ?? ''), c.reqs.map((x) => `\`${x}\``).join(' '), c.budget != null ? String(c.budget) : '', `\`${c.file}\``]
        : [c.id, cell(c.title), c.reqs.map((x) => `\`${x}\``).join(' '), `\`${c.file}\``];
    })), '');
  }
  out.push('## The ease test', '', 'Every journey is scored out of ten, one point each:', '', ...req.easeCriteria.map((e) => `- \`${e.id}\`: ${e.text}`), '');
  out.push('## Not built yet, on purpose', '', ...req.notYetBuilt.map((x) => `- ${x}`), '');
  return out.join('\n');
}

function requirementsPage(r: Repo, mods: ModuleFacts[], tests: TestCase[]): string {
  const req = requirements(r);
  const theirs = moduleReqs(mods);
  const all = checks(r);
  const rules = new Map<string, Rule[]>();
  for (const rule of RULE_LIST) for (const id of rule.reqs) rules.set(id, [...(rules.get(id) ?? []), rule]);
  const out = [GENERATED('evals/requirements.json, src/help/guide.ts, src/spec/rules.ts, the tests and the evals'), '# The core requirements', '',
    `Every requirement in \`evals/requirements.json\` that no module owns (a module’s are in its section). For each: the rule that implements it (when it is one of the core rules), the Help article that explains it and the screens that article covers, the tests tagged with it (\`[ID]\` in a test’s title), and the journeys and checks that exercise it.`, '',
    `${UNCLEAR} a requirement with no rule, test or journey listed is checked only by the screens and Help named, or not yet by anything automatic; its words are the spec.`, ''];
  const byArea = new Map<string, typeof req.requirements>();
  for (const q of req.requirements.filter((q) => !theirs.has(q.id))) byArea.set(q.area, [...(byArea.get(q.area) ?? []), q]);
  for (const [area, qs] of byArea) {
    out.push(`## ${area}`, '');
    for (const q of qs) {
      const arts = ARTICLES.filter((a) => !a.module && a.reqs.includes(q.id));
      const t = tests.filter((x) => x.reqs.includes(q.id));
      const c = all.filter((x) => x.reqs.includes(q.id));
      const rs = rules.get(q.id) ?? [];
      out.push(`### ${q.id}`, '', q.text, '');
      if (rs.length) out.push(`- **Rule:** ${rs.map((x) => `[${x.title}](rules/${x.id}.md)`).join(', ')}`);
      if (arts.length) out.push(`- **Help:** ${arts.map((a) => `“${a.title}” (\`${a.id}\`)${a.screens.length ? `, screens ${a.screens.map((s) => `\`${s}\``).join(', ')}` : ''}`).join('; ')}`);
      if (t.length) out.push(`- **Tests:** ${[...new Set(t.map((x) => x.file))].map((f) => `\`${f}\` (${t.filter((x) => x.file === f).length})`).join(', ')}`);
      if (c.length) out.push(`- **Journeys and checks:** ${c.map((x) => x.id).join(', ')}`);
      out.push('');
    }
  }
  return out.join('\n');
}

