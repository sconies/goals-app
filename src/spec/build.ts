/* ---------- rules ---------- */

/** A rule's tests: `file` (every test in a unit test file; in an eval file, those tagged with the rule's requirements) or
    `file#describe` (only the tests inside that describe block). */
const testsFor = (tests: TestCase[], specs: string[], reqs: string[]) => tests.filter((t) => specs.some((sp) => {
  const [file, within] = sp.split('#');
  return t.file === file && (within ? t.within[0] === within : t.file.startsWith('src/') || t.reqs.some((r) => reqs.includes(r)));
}));

function rulePage(rule: Rule, tests: TestCase[], reqText: Map<string, string>): string {
  const out = [GENERATED('src/spec/rules.ts and the code it names'), `# ${rule.title}`, '', rule.summary, '', '## The rule', rule.body, ''];
  out.push('## Worked examples', '', 'Each is run against the real rule by `src/spec/spec.test.ts`: the result is what the code gives.', '');
  out.push(table(['Given', 'The rule gives'], rule.examples.map((e) => [cell(e.given), `\`${cell(e.then)}\``])), '');
  if (rule.unclear?.length) out.push('## Not self-explanatory', '', ...rule.unclear.map((u) => `- ${UNCLEAR} ${u}`), '');
  out.push('## Where it lives', '', ...rule.code.map((c) => `- ${link(3, c.file)}: ${c.names.map((x) => `\`${x}\``).join(', ')}`), '');
  out.push('## Requirements', '', ...rule.reqs.map((r) => `- \`${r}\`: ${reqText.get(r) ?? '(not in evals/requirements.json)'}`), '');
  const mine = testsFor(tests, rule.tests, rule.reqs);
  out.push('## Tests that check it', '');
  for (const f of [...new Set(rule.tests.map((x) => x.split('#')[0]!))]) {
    const here = mine.filter((t) => t.file === f);
    out.push(`### ${link(3, f)}`, '', ...(here.length ? here.map((t) => `- ${[...t.within, t.title].map((x) => cell(x)).join(' › ')}`) : ['_None tagged with these requirements._']), '');
  }
  return out.join('\n');
}

