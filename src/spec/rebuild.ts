/** A module's rebuild stage, as its module.json writes it under `rebuild`. Every module has one (CI checks:
    scripts/check-rebuild.mjs); an outline counts until its drill exists. */
export interface ModuleRebuild {
  /** `drill`: the harness scores it. `outline`: entry and exit criteria, checked by hand until it has a drill. */
  status: 'drill' | 'outline';
  /** What this stage builds, in a sentence or two. */
  builds: string;
  /** What must be true before it starts, beyond the stages before it. */
  entry: string[];
  /** What must be true when it is done, beyond its requirements and journeys (listed from module.json by themselves). */
  exit: string[];
  /** What the kit doesn't hold yet for this stage, so a rebuild would have to guess. */
  gaps: string[];
}
export type ModuleWithRebuild = ModuleFacts & { rebuild?: ModuleRebuild };

export interface Stage {
  n: number;
  /** The file under spec/rebuild/. */
  file: string;
  title: string;
  builds: string;
  status: 'drill' | 'outline';
  module?: string;
}

const GENERATED = '<!-- Generated by npm run spec from src/spec/rebuild.ts. Edit the code, not this file. -->\n\n';
const RULES_STAGE1 = RULE_PAGES.filter(([id]) => id !== 'change-engine');
const ruleLinks = (pages: typeof RULE_PAGES, depth = '../core/rules/') => pages.map(([id, title]) => `[${title}](${depth}${id}.md)`).join(', ');

/** Modules in an order each can be built in: after everything it needs, then by id. */
export function moduleOrder<T extends Pick<ModuleFacts, 'id' | 'needs'>>(mods: T[]): T[] {
  const out: T[] = [], done = new Set<string>(), left = [...mods].sort((a, b) => a.id.localeCompare(b.id));
  while (left.length) {
    const i = left.findIndex((m) => m.needs.every((n) => done.has(n) || !mods.some((x) => x.id === n)));
    const [m] = left.splice(i < 0 ? 0 : i, 1);
    out.push(m!); done.add(m!.id);
  }
  return out;
}

/** Every stage, in order: the three core stages, then one per module that has a `rebuild` in its module.json. */
export function stages(mods: ModuleWithRebuild[]): Stage[] {
  const core: Stage[] = [
    { n: 1, file: 'stage-1-core-rules.md', title: 'The core rules', status: 'drill', builds: 'Weeks and plans, a goal’s status, the projection, what a check-in must say, flags and needs attention, and the scorecard: pure functions over the records, with no screens and no database.' },
    { n: 2, file: 'stage-2-core-data.md', title: 'The core data and the change engine', status: 'outline', builds: 'Every core record stored, the change log with undo, and the change engine that takes many changes at once and checks them with the stage 1 rules.' },
    { n: 3, file: 'stage-3-core-screens.md', title: 'The core screens and journeys', status: 'outline', builds: 'Each core screen with its route, named parts and one main action, so a person can do every core journey.' },
  ];
  const ordered = moduleOrder(mods.filter((m) => m.rebuild));
  return [...core, ...ordered.map((m, i): Stage => ({ n: 4 + i, file: `stage-${4 + i}-module-${m.id}.md`, title: `Module: ${m.name}`, status: m.rebuild!.status, builds: m.rebuild!.builds, module: m.id }))];
}

