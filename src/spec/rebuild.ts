/* The rebuild kit (backlog 8k): spec/rebuild/, a staged guide to rebuilding Faro from spec/ and llms.txt alone, with a
   drill for each stage that has one. Made by `npm run spec` with the rest of the spec, so it can't drift: the stages come
   from the core's parts and from each module's module.json (its `rebuild` field), and the drill harness is copied from
   scripts/drill.mjs to spec/rebuild/drill.mjs so a copy of spec/ carries it. Pure: the caller reads the files. */
import type { ModuleFacts } from '../core/module';
