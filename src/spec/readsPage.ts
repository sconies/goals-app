/* spec/rebuild/reads.md (KT gap 9): what each action and each goal's summary row reads, worked out by running them on
   the demo workspace (src/spec/readsRun.ts) and noting every field read (src/spec/reads.ts). */
import { wholeList, type ListReads } from './reads';
import { actionReads, sliceProof, type ActionReads } from './readsRun';

const GENERATED = '<!-- Generated by npm run spec from src/spec/readsPage.ts, src/spec/readsRun.ts and src/spec/readsSamples.ts. Edit those, not this file. -->\n\n';
const n = (x: number) => x.toLocaleString('en-GB');
const listName = (l: string) => `\`${l}\``;
const one = (r: ListReads) => `${listName(r.list)} ${n(r.used)} of ${n(r.total)}${r.by.length ? `, past the rest by ${r.by.map((b) => `\`${b}\``).join(', ')}` : ''}`;

/** The most records of each list any goal's row read. */
function most(rows: ListReads[][]): string[] {
  const m = new Map<string, number>();
  for (const reads of rows) for (const r of reads) m.set(r.list, Math.max(m.get(r.list) ?? 0, r.used));
  return [...m].sort(([a], [b]) => a.localeCompare(b)).map(([l, k]) => `${listName(l)} ${n(k)}`);
}

function actionsTable(all: ActionReads[]): string[] {
  return [
    '| Action | As | On the demo | Records used (of the list), and what the rest were looked past by | Every record of |',
    '|---|---|---|---|---|',
    ...all.map((a) => `| \`${a.action}\` | ${a.as} | ${a.outcome === 'refused' ? `refused: “${a.said.replace(/\|/g, '/')}”` : a.outcome} | ${a.reads.filter((r) => r.used > 0 || r.by.length).map(one).join('; ') || 'nothing in the workspace’s lists'} | ${a.reads.filter(wholeList).map((r) => listName(r.list)).join(', ') || '—'} |`),
  ];
}

export async function readsPage(): Promise<string> {
  const proof = sliceProof();
  const same = proof.filter((p) => p.same).length;
  const actions = await actionReads();
  const whole = actions.filter((a) => a.reads.some(wholeList));
  return GENERATED + [
    '# What each action and summary reads',
    '',
    `For a server that reads only what it needs ([R4](../requirements/internal/r4-scale-and-safety.md): nothing loads a whole workspace; [the ports at company scale](ports-at-scale.md), step 3). Worked out by running each one on [the demo workspace](../conformance/workspace.json), not by reading the code: every list is wrapped so each field a rule reads off a record is noted. A record whose only fields read are keys (\`id\`, or a field ending in \`Id\` or \`Ids\`) was looked past, as an index would; a record with any other field read was **used**, and is what a server has to fetch. [Accepting scale](scale.md) has a company-size workspace to time it on.`,
    '',
    '## A goal’s summary row',
    '',
    `A summary row (R4, rule 2) is a goal’s summary (status, what the numbers say, the projection, the scorecard), its flags, whether it needs attention, and whether it is being handled. It reads **one goal’s own records**:`,
    '',
    '- the goal, its parent and its children, and the other goals an ask it shares names (for their titles);',
    '- its check-ins and its decisions (reviewed, noted, the calls in reviews);',
    '- the asks that name it, and the reviews those and its decisions were made in;',
    '- the people any of them name (its owner, the authors, whoever decided, asked or answered), its team, its lead and the people in it;',
    '- the cycle, and today.',
    '',
    `Proved for every live goal of the demo (${same} of ${proof.length}): its row worked out from those records alone is the same, field for field, as from the whole workspace (\`src/spec/reads.test.ts\`). So a save works out again the rows of the goals it touched from their own records, and the week’s turn does each goal from its own records, in any order or in parallel.`,
    '',
    `The most any one goal’s row used: ${most(proof.map((p) => p.reads)).join(', ')}. **Being handled** alone used: ${most(proof.map((p) => p.handled)).join(', ')}. That is how it is worked out without the workspace: [accepting scale](scale.md#being-handled-from-one-goals-records).`,
    '',
    'Faro’s own code builds an index of every check-in the first time it is asked for one goal’s, which is quick in a browser and reads every record; on a server, that index is the database’s.',
    '',
    '## Each action',
    '',
    `Each action of [the command port](../core/actions.md), run once as the person named, with an input picked from the demo (\`src/spec/readsSamples.ts\`). A refused action shows what it read before it said no, with its words: the demo’s date or records don’t allow it, and it reads more once allowed. **Every record of** names the lists an action read whole: what a server has to narrow first. ${whole.length} of ${actions.length} actions do today, because the rules that take the whole workspace (\`scripts/whole-workspace.json\`) look through a list where an index would do. The goal an action names is looked up by its id (\`goals … past the rest by id\`), which a server does with its key.`,
    '',
    ...actionsTable(actions),
  ].join('\n') + '\n';
}
