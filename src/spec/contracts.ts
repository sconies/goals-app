/* The port contracts as data, in the kit (handoff kit review, gap 1(b)): spec/conformance/contracts/<port>.json, one per
   port whose contract is written as cases (src/ports/contracts/cases), and a README saying how a build runs them through
   the drill harness. Pure: buildSpec (build.ts) writes what this returns. */
import { PREFS_CONTRACT } from '../ports/contracts/cases/prefs';
import { SEARCH_CONTRACT } from '../ports/contracts/cases/search';
import type { Contract } from '../ports/contracts/cases/format';

/** Every contract written as data, in the order a build is asked to pass them. The goals and store contracts join when
    they move to cases (track 4's next changes). */
export const CONTRACTS: Contract[] = [SEARCH_CONTRACT, PREFS_CONTRACT];

/** What each key of a `then` checks: the words the README gives (cases/format.ts, `Then`, says the same). */
const THEN_KEYS: [string, string][] = [
  ['select', 'a path into the answer that the other keys look at: `total`, `rows[0].name`, `rows[].id` (every row’s id), `[].id` when the answer is a list. Inside `all` and `anyOf`, each path starts from the whole answer again.'],
  ['equals', 'equal as JSON: the same keys (a key left out and one holding nothing are the same), the same values, lists in the same order.'],
  ['has', 'at least this: an object’s keys as deep as given (others may be there too), a list’s items one for one.'],
  ['includes', 'a list holding each of these, anywhere in it.'],
  ['excludes', 'a list holding none of these.'],
  ['length', 'a list or text exactly this long.'],
  ['maxLength', 'a list or text no longer than this.'],
  ['distinct', 'a list with no item twice.'],
  ['ordered', '`"text"`: A to Z in the language’s own order; `{ "rank": { … } }`: by each item’s rank, highest first, ties in any order (stale and at risk tie, so worst first is checked this way, not by a fixed list).'],
  ['throws', 'the operation refuses: the shim answers `{ "error": … }`, in any words.'],
  ['absent', 'nothing there: the key is left out, or null.'],
  ['all', 'every one of these holds.'],
  ['anyOf', 'at least one of these holds: where the contract accepts either of two answers (a near miss is optional).'],
];

const code = (s: string) => `\`${s}\``;

function readme(): string {
  return [
    '<!-- Generated by npm run spec from src/spec/contracts.ts. Edit the code, not this file. -->',
    '',
    '# The port contracts, as data',
    '',
    'What any build’s ports must do, as cases a harness runs: the same cases Faro’s own tests run on its adapters (`src/ports/contracts/`). A team that copies Faro’s code passes them with its adapters; a rebuild passes them with its own ports, through a small shim.',
    '',
    '## A contract file',
    '',
    'Each `<port>.json` holds `port` (the name the shim is asked by), `about`, `ops` (each operation the shim answers, with its arguments and what it does), `given` (what a case starts from) and `cases`. A case is `{ "name", "given"?, "steps" }`: a sentence saying what any build must do, its own `given` when it doesn’t start from the contract’s, and its steps, each `{ "when": { "op", "args" }, "then" }`. A step with `pages` calls its operation again with the last answer’s `next` put in as `after` (in the argument at `pages.arg`), until `next` is null or `pages.max` calls; `pages.each` is checked on every answer, and `then` on `{ "pages", "rows" }`: how many calls were made, and every page’s rows in order.',
    '',
    'What a `then` checks (every key given must hold; an empty `then` only asks that the operation doesn’t refuse):',
    '',
    ...THEN_KEYS.map(([k, v]) => `- ${code(k)}: ${v}`),
    '',
    '## The shim',
    '',
    'A command that answers one JSON request per line on its standard input with one JSON answer per line on its standard output, in order, and nothing else on standard output (write anything else to standard error). A request is `{ "port", "op", "args" }`; the answer is `{ "ok": <the answer> }`, or `{ "error": "<words>" }` when the operation refuses. Each case starts with `{ "port", "op": "given", "args": [<given>] }`: start that port afresh from it, and answer `{ "ok": null }`. An operation with no answer answers `{ "ok": null }`.',
    '',
    'Name it in `drill.json` beside (or instead of) `run`, and the harness runs every contract here through it:',
    '',
    '```',
    '{ "stage": 1, "run": "node main.mjs", "shim": "node shim.mjs" }',
    '{ "shim": "node shim.mjs", "contracts": ["search"] }      only these contracts, and no CSV files',
    'node spec/rebuild/drill.mjs rebuild --contracts prefs      one contract while you work',
    '```',
    '',
    'It prints each contract’s count of cases that pass, then each failing case with what went wrong, and exits 0 only when every case passes (and every scored CSV file matches).',
    '',
    '## The contracts',
    '',
    ...CONTRACTS.flatMap((c) => [
      `### [${c.port}](${c.port}.json)`,
      '',
      c.about,
      '',
      ...Object.entries(c.ops).map(([op, what]) => `- ${code(op)}: ${what}`),
      '',
      `Its ${c.cases.length} cases:`,
      '',
      ...c.cases.map((x) => `1. ${x.name}`),
      '',
    ]),
    '**Not yet as data:** the goals contract (`goalsContract`, whose cases are `goals.csv` today) and the goals store’s (`storeContract`) are still only in Faro’s code; they move here next.',
    '',
  ].join('\n');
}

/** spec/conformance/contracts/: each contract's JSON, and the README. */
export function contractFiles(): Record<string, string> {
  const out: Record<string, string> = { 'spec/conformance/contracts/README.md': readme() };
  for (const c of CONTRACTS) out[`spec/conformance/contracts/${c.port}.json`] = JSON.stringify(c, null, 2) + '\n';
  return out;
}
