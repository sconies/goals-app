// round trip: export, read back, run the engine
import { load } from '../../../s1.mjs';
import { makeRules, WORKSPACE_NAME } from '../../../stage3.mjs';
import { workbook } from '../export.mjs';
import { readFile, readTables, run, groups, readLine } from '../importer.mjs';
const [,, A2, A3, A4] = process.argv;
const ws = A2 || new URL('../../../../spec/conformance/workspace.json', import.meta.url).pathname;
const { S1 } = await load(ws);
const W = S1.W; const R = makeRules(W, S1);
const viewer = A3 || 'amara';
const moment = (A4 || W.builtFor.slice(0,10)) + 'T12:00:00.000Z';
const ctx = { W, S1, R, viewer, moment, week: S1.currentWeek(moment), wsName: WORKSPACE_NAME, todayIso: moment.slice(0,10), nowIso: () => moment };
let t = Date.now();
const buf = workbook(ctx);
const sheets = readFile(buf, 'x.xlsx');
const rt = readTables(sheets);
console.log('export+read ms', Date.now() - t, buf.length, readLine(rt));
t = Date.now();
const res = run(ctx, rt);
console.log('engine ms', Date.now() - t, 'items', res.items.length, 'unchanged', res.unchanged, 'issues', res.issues.length);
for (const g of groups(res, rt).slice(0, 12)) console.log(g.level, g.kind, g.n, g.title, '|', g.lines[0].message, g.where);
for (const it of res.items.slice(0, 8)) console.log(it.kind, it.name, JSON.stringify(it.diffs));
